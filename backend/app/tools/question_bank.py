# 级别 -> 难度提示，供出题官参考
LEVEL_HINT = {
    "初级": "面向基础概念与常见用法，能讲清原理即可，不要求深入源码",
    "中级": "要求理解底层机制、能分析常见问题的原因，具备一定实操经验",
    "高级": "要求掌握设计权衡、性能与稳定性意识，能从源码/架构层面分析",
    "专家": "要求体系化认知，能主导方案设计、预判风险并做跨团队技术决策",
}


def query_question_bank(track: str, sub: str = "", level: str = "") -> str:
    """查询内置高频面试题库，返回经典题目列表文本。

    Args:
        track: 主技术方向，如「后端开发」「前端开发」「算法」
        sub: 细分方向（可选），如「Java/JVM」「数据库与SQL」，留空则返回该主方向全部
        level: 候选人级别（可选），用于附加难度提示

    Returns:
        题库文本（Markdown 列表），找不到时返回相近方向提示
    """
    track_data = QUESTION_BANK.get(track)
    if not track_data:
        # 模糊匹配：包含关系
        for k in QUESTION_BANK:
            if track and (track in k or k in track):
                track_data = QUESTION_BANK[k]
                track = k
                break
    if not track_data:
        return (
            "题库中没有该方向的条目。请直接凭借你的专业知识出题，"
            "覆盖基础、场景、排查与深挖四类题型。"
        )

    lines = [f"# {track} 高频面试题库（供参考，可结合简历改造）"]
    if sub and sub != "随机":
        items = track_data.get(sub)
        if not items:
            for k in track_data:
                if sub in k or k in sub:
                    items = track_data[k]
                    break
        if items:
            lines.append(f"## {sub}")
            lines.extend(f"- {q}" for q in items)
        else:
            lines.append(f"（未找到「{sub}」的条目，以下是该主方向全部子类）")
            for k, v in track_data.items():
                lines.append(f"## {k}")
                lines.extend(f"- {q}" for q in v)
    else:
        for k, v in track_data.items():
            lines.append(f"## {k}")
            lines.extend(f"- {q}" for q in v)

    if level and level in LEVEL_HINT:
        lines.append("")
        lines.append(f"难度参考（{level}）：{LEVEL_HINT[level]}")

    return "\n".join(lines)
